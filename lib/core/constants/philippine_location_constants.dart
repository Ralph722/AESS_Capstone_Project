  static List<String> provincesForRegion(String? region) {
    if (region == null || region.isEmpty) return allProvinces;
    return provincesByRegion[region] ?? allProvinces;
  }

  static String? regionForProvince(String province) {
    for (final entry in provincesByRegion.entries) {
      if (entry.value.contains(province)) return entry.key;
    }
    return null;
  }
